@dataclass(frozen=True, slots=True)
class WordEntry:
    text: str
    category: Category
    aliases: tuple[str, ...] = ()

    @property
    def answers(self) -> tuple[str, ...]:
        return (self.text, *self.aliases)

    def to_dict(self) -> dict[str, object]:
        return {"text": self.text, "category": self.category, "aliases": list(self.aliases)}


