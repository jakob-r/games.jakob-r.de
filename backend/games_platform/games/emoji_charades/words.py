def _parse(language: Language) -> list[WordEntry]:
    entries: list[WordEntry] = []
    for category, lines in _RAW_WORDS[language].items():
        for line in lines:
            parts = [p.strip() for p in line.split("|") if p.strip()]
            entries.append(WordEntry(text=parts[0], category=category, aliases=tuple(parts[1:])))
    return entries


WORDS: dict[Language, list[WordEntry]] = {lang: _parse(lang) for lang in SUPPORTED_LANGUAGES}


def normalize_language(language: str) -> Language:
    lang = language.strip().lower()
    return lang if lang in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE
