"""Curated Emoji Charades word lists.

Each entry is ``"Display text|alias|alias"``. The first part is shown to the explainer
and revealed at the end of the round; every part (display text included) is accepted
as a correct remote guess. Add or remove lines freely to tune the selection, but skip
words that a single emoji from the explainer palette (frontend `emojis.ts`) already
shows on its own (e.g. Balloon 🎈, Pizza 🍕, Penguin 🐧).
"""

from __future__ import annotations

from dataclasses import dataclass

