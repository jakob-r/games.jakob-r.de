"""North South Sort location dataset.

``locations.json`` is generated by ``generate_locations.py`` (``make locations``) from
Wikidata plus an LLM curation pass, and committed to the repo.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, fields
from functools import cache
from pathlib import Path
from typing import Literal, get_args

type Category = Literal["city", "landmark", "event"]
type Continent = Literal[
    "europe", "asia", "africa", "north_america", "south_america", "oceania", "antarctica"
]
type BoundsSource = Literal["extreme_points", "area", "default"]

CATEGORIES: tuple[Category, ...] = get_args(Category.__value__)
CONTINENTS: tuple[Continent, ...] = get_args(Continent.__value__)
CATEGORY_POINTS: dict[Category, int] = {"city": 1, "landmark": 2, "event": 3}

LOCATIONS_PATH = Path(__file__).with_name("locations.json")


@dataclass(frozen=True, slots=True)
class Location:
    id: str  # Wikidata QID
    category: Category
    name_en: str
    name_de: str
    lat: float
    lon: float
    min_lat: float
    max_lat: float
    min_lon: float
    max_lon: float
    bounds_source: BoundsSource
    description_en: str
    description_de: str
    wikipedia_en: str
    wikipedia_de: str | None
    country_en: str | None
    country_de: str | None
    continent: Continent
    fame: int  # 1 (obscure) .. 5 (world famous)
    sitelinks: int

    @classmethod
    def from_dict(cls, data: dict) -> Location:
        names = {f.name for f in fields(cls)}
        return cls(**{k: v for k, v in data.items() if k in names})


@cache
def load_locations(path: Path = LOCATIONS_PATH) -> tuple[Location, ...]:
    data = json.loads(path.read_text(encoding="utf-8"))
    return tuple(Location.from_dict(item) for item in data["locations"])
